function byRank(first, second) {
  return (first.rank ?? Number.MAX_SAFE_INTEGER) - (second.rank ?? Number.MAX_SAFE_INTEGER);
}

export const featuredProducts = productCatalog.flatMap((product) => product.featured
  ? [{ ...product.featured, id: product.id, img: product.image, link: product.link }]
  : []);

export const categoryProducts = productCatalog.flatMap((product) => product.categoryCard
  ? [{ ...product.categoryCard, id: product.id, image: product.image, link: product.link }]
  : []).sort(byRank);

export const trendingProducts = productCatalog.filter((product) => product.trending !== false)
  .map((product) => ({
    id: product.id,
    name: product.name,
    img: product.image,
    link: product.link,
    category: product.group,
    badge: "Trending Pick",
    nameLines: 2,
    ...product.trending,
  })).sort(byRank);

export const weeklyDeals = productCatalog.flatMap((product) => product.weekly
  ? [{ name: product.name, link: product.link, leftImage: product.image, rightImage: product.image, ...product.weekly }]
  : []).sort(byRank);

export function productReviewUrl(productId) {
  return `/reviews.html?product=${encodeURIComponent(productId)}#review-form`;
}
